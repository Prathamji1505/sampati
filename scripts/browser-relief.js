async page => {
  const check = (ok, message) => { if (!ok) throw new Error(message) }
  const origin = 'http://127.0.0.1:5173'
  const suffix = crypto.randomUUID().replaceAll('-', '').slice(0,14)
  const generated = []
  const errors = []
  let expectedConflictPath = ''
  await page.goto(origin + '/')
  await page.context().clearCookies()
  page.on('console', message => { if (message.type() === 'error' && !(expectedConflictPath && message.location().url.endsWith(expectedConflictPath) && message.text().includes('409'))) errors.push(message.text()) })
  page.on('pageerror', error => errors.push(error.message))
  const get = async (target, path) => (await target.request.get(origin + '/api' + path)).json()
  const post = async (target, path, body, csrf) => target.request.post(origin + '/api' + path, { headers: { 'X-Sampati-Request': '1', 'X-CSRF-Token': csrf }, data: body })
  async function signup(target, index) {
    await target.goto(origin + '/#register')
    await target.getByLabel('Your name', { exact: true }).fill('Browser QA relief ' + index)
    await target.getByLabel('Organisation name', { exact: true }).fill('Browser QA organisation relief ' + suffix + index)
    await target.getByLabel('Username', { exact: true }).fill('qa-browser-' + suffix + index)
    await target.getByLabel('Password', { exact: true }).fill('Fictional QA ' + crypto.randomUUID())
    await target.getByRole('button', { name: 'Create account & workspace', exact: true }).click()
    await target.getByRole('heading', { name: 'Aircraft register', exact: true }).waitFor()
    const identity = await get(target, '/auth/session')
    generated.push(identity.user.id)
    await page.evaluate(ids => sessionStorage.setItem('sampati-relief-qa-ids', JSON.stringify(ids)), generated)
    return identity
  }
  async function navigate(target, name) {
    if (await target.getByRole('button', { name: 'Toggle navigation', exact: true }).isVisible()) await target.getByRole('button', { name: 'Toggle navigation', exact: true }).click()
    await target.getByRole('navigation', { name: 'Main navigation' }).getByRole('button', { name, exact: true }).click()
  }
  async function capture(kind) {
    for (const width of [1440,1024,390,320]) {
      await page.setViewportSize({ width, height:1000 })
      await page.evaluate(async()=>{await document.fonts.ready;document.activeElement?.blur();scrollTo(0,0);await new Promise(resolve=>requestAnimationFrame(()=>requestAnimationFrame(resolve)))})
      const dimensions = await page.evaluate(()=>({viewport:innerWidth,document:document.documentElement.scrollWidth}))
      check(dimensions.document <= dimensions.viewport, kind + ' overflow at ' + width)
      await page.screenshot({path:'.impeccable/review/relief-'+kind+'-'+width+'.png',fullPage:true})
    }
    await page.setViewportSize({width:1440,height:1000})
  }
  async function changeStatus(status, reason) {
    await page.getByRole('combobox', {name:'Next status',exact:true}).selectOption(status)
    await page.getByLabel('Reason for status change', {exact:true}).fill(reason)
    await page.getByRole('button',{name:'Update status',exact:true}).click()
    await page.getByRole('status').filter({hasText:'Status updated to'}).waitFor()
  }
  await page.setViewportSize({width:1440,height:1000})
  await page.goto(origin+'/#demo/relief')
  await page.getByRole('button',{name:'Open DEMO-REL-002 request',exact:true}).waitFor()
  check(await page.getByRole('button',{name:'New request',exact:true}).isDisabled(),'Demo creation is enabled')
  await page.getByRole('button',{name:'Open DEMO-REL-002 request',exact:true}).click()
  await page.getByRole('heading',{name:'Request history',exact:true}).waitFor()
  check(await page.getByRole('heading',{name:'Review and status',exact:true}).count()===0,'Demo exposes status mutation')
  const owner = await signup(page,1)
  await navigate(page,'Relief requests')
  await page.getByRole('heading',{name:'Your relief request register starts here.',exact:true}).waitFor()
  await page.getByRole('button',{name:'New request',exact:true}).click()
  await page.getByRole('button',{name:'Use fictional example',exact:true}).click()
  await page.getByLabel('Request reference',{exact:true}).fill('QA-REL-001')
  await page.getByLabel('Quantity',{exact:true}).fill('12.125')
  await capture('form')
  await page.getByRole('button',{name:'Save draft',exact:true}).click()
  await page.getByRole('heading',{name:'Request history',exact:true}).waitFor()
  let saved = (await get(page,'/relief-requests?q=QA-REL-001')).items[0]
  check(saved.version===1 && saved.quantity==='12.125','Draft/quantity was not saved')
  const firstId = saved.id
  await page.getByRole('button',{name:'Edit draft',exact:true}).click()
  await page.getByLabel('Quantity',{exact:true}).fill('15.5')
  await page.getByLabel('Reason for correction',{exact:true}).fill('Fictional source count corrected.')
  await page.getByRole('button',{name:'Save correction',exact:true}).click()
  await page.getByRole('heading',{name:'Request history',exact:true}).waitFor()
  saved = (await get(page,'/relief-requests/'+firstId)).request
  check(saved.version===2 && saved.quantity==='15.5','Correction did not persist')
  await page.locator('.relief-history > li').first().getByText('View recorded changes',{exact:true}).click()
  check((await page.locator('.relief-history > li').first().textContent()).includes('12.125'),'Original quantity missing from audit')
  await changeStatus('submitted','Fictional request ready for review.')
  await changeStatus('reviewed','Fictional supply details checked; no delivery recorded.')
  check(await page.getByRole('button',{name:'Edit draft',exact:true}).count()===0,'Reviewed request can be edited without returning to draft')
  await capture('detail')
  await changeStatus('draft','Return for source correction.')
  await changeStatus('cancelled','Fictional request withdrawn by its source.')
  check(await page.getByRole('heading',{name:'Review and status',exact:true}).count()===0,'Cancelled request can transition')
  await page.getByRole('button',{name:'Back to requests',exact:true}).click()
  await page.getByRole('button',{name:'New request',exact:true}).click()
  await page.getByRole('button',{name:'Use fictional example',exact:true}).click()
  await page.getByLabel('Request reference',{exact:true}).fill('QA-REL-002')
  await page.getByRole('button',{name:'Save draft',exact:true}).click()
  await page.getByRole('heading',{name:'Request history',exact:true}).waitFor()
  const second = (await get(page,'/relief-requests?q=QA-REL-002')).items[0]
  const raw = {requesting_organisation:'Fictional Bulk Desk',locality:'Fictional Valley',category:'food',item_name:'Fictional food boxes',quantity:'20',unit:'boxes',needed_by:new Date(Date.now()+86400000).toISOString(),source_name:'Fictional QA log',note:''}
  for(let index=1;index<=21;index++) {
    const response = await post(page,'/relief-requests',{...raw,reference:'QA-BULK-'+String(index).padStart(3,'0'),submission_key:crypto.randomUUID()},owner.csrf_token)
    check(response.status()===201,'Bulk fixture creation failed')
  }
  await page.getByRole('button',{name:'Back to requests',exact:true}).click()
  await page.getByText('Page 1 of 2',{exact:true}).waitFor()
  await page.getByRole('button',{name:'Next requests',exact:true}).click()
  await page.getByText('Page 2 of 2',{exact:true}).waitFor()
  check(await page.locator('.relief-table tbody tr').count()===3,'Second page should have 3 requests')
  await page.getByRole('textbox',{name:'Search relief requests',exact:true}).fill('QA-REL-')
  await page.getByRole('button',{name:'Open QA-REL-001 request',exact:true}).waitFor()
  await page.waitForFunction(()=>document.querySelectorAll('.relief-table tbody tr').length===2)
  await capture('list')
  await page.getByRole('button',{name:'Open QA-REL-002 request',exact:true}).click()
  await page.getByRole('button',{name:'Edit draft',exact:true}).waitFor()
  const remote = await post(page,'/relief-requests/'+second.id+'/status',{status:'submitted',expected_version:1,reason:'Fictional concurrent review submission.'},owner.csrf_token)
  check(remote.status()===200,'Background update failed')
  await page.getByRole('button',{name:'Edit draft',exact:true}).click()
  await page.getByLabel('Quantity',{exact:true}).fill('99')
  await page.getByLabel('Reason for correction',{exact:true}).fill('Fictional stale correction attempt.')
  expectedConflictPath = '/api/relief-requests/'+second.id
  await page.getByRole('button',{name:'Save correction',exact:true}).click()
  await page.getByRole('alert').filter({hasText:'This request changed after you opened it.'}).waitFor()
  check((await get(page,'/relief-requests/'+second.id)).request.quantity===second.quantity,'Stale edit overwrote accepted request')
  await page.getByRole('button',{name:'Cancel editing',exact:true}).click()
  await page.getByRole('button',{name:'Refresh details',exact:true}).click()
  await page.getByRole('heading',{name:'Review and status',exact:true}).waitFor()
  expectedConflictPath = ''
  const context2 = await page.context().browser().newContext({viewport:{width:1280,height:900}})
  const other = await context2.newPage()
  const outsider = await signup(other,2)
  check((await other.request.get(origin+'/api/relief-requests/'+firstId)).status()===404,'Foreign organisation read request details')
  check((await get(other,'/relief-requests')).total===0,'Foreign organisation list leaked requests')
  const ownRequest = await post(other,'/relief-requests',{...raw,reference:'QA-REL-001',requesting_organisation:'Fictional Second Desk',submission_key:crypto.randomUUID()},outsider.csrf_token)
  check(ownRequest.status()===201,'Reference incorrectly reserved across organisations')
  const invitation = await (await post(page,'/team/invitations',{username:outsider.user.username,role:'viewer'},owner.csrf_token)).json()
  const joined = await post(other,'/team/invitations/accept',{token:invitation.token},outsider.csrf_token)
  check(joined.status()===200,'Viewer invitation failed')
  await other.goto(origin+'/#relief')
  // The invitation above used the API directly; restore the page's session state.
  await other.reload()
  await other.getByRole('button',{name:'New request',exact:true}).waitFor()
  check(await other.getByRole('button',{name:'New request',exact:true}).isDisabled(),'Viewer can create requests')
  await other.getByRole('textbox',{name:'Search relief requests',exact:true}).fill('QA-BULK-001')
  await other.getByRole('button',{name:'Open QA-BULK-001 request',exact:true}).click()
  await other.getByRole('heading',{name:'Request history',exact:true}).waitFor()
  check(await other.getByRole('button',{name:'Edit draft',exact:true}).count()===0 && await other.getByRole('heading',{name:'Review and status',exact:true}).count()===0,'Viewer mutation controls shown')
  await other.getByRole('combobox',{name:'Workspace',exact:true}).selectOption(outsider.workspace.id)
  await other.getByRole('heading',{name:'Aircraft register',exact:true}).waitFor()
  await navigate(other,'Relief requests')
  await other.getByRole('cell',{name:/Fictional Second Desk/}).waitFor()
  await context2.close()
  const retryContext = await page.context().browser().newContext({viewport:{width:390,height:844},isMobile:true,hasTouch:true})
  await retryContext.addCookies(await page.context().cookies())
  const retry = await retryContext.newPage()
  await retry.goto(origin+'/#relief')
  await retry.getByRole('button',{name:'New request',exact:true}).click()
  await retry.getByRole('button',{name:'Use fictional example',exact:true}).click()
  await retry.getByLabel('Request reference',{exact:true}).fill('QA-RETRY-001')
  check(await retry.getByLabel('Quantity',{exact:true}).evaluate(el=>parseFloat(getComputedStyle(el).fontSize)>=16),'Phone quantity text below 16px')
  check(await retry.getByRole('button',{name:'Save draft',exact:true}).evaluate(el=>el.getBoundingClientRect().height>=44),'Touch save action below 44px')
  let drop = true
  await retry.route('**/api/relief-requests',async route=>{if(drop && route.request().method()==='POST'){drop=false;await route.fetch();await route.abort('failed')}else await route.continue()})
  await retry.getByRole('button',{name:'Save draft',exact:true}).click()
  await retry.getByRole('alert').filter({hasText:'The local server could not be reached.'}).waitFor()
  await retry.getByRole('button',{name:'Save draft',exact:true}).click()
  await retry.getByRole('heading',{name:'Request history',exact:true}).waitFor()
  const retried = await get(page,'/relief-requests?q=QA-RETRY-001')
  check(retried.total===1 && (await get(page,'/relief-requests/'+retried.items[0].id)).events.length===1,'Lost response retry created duplicate data/history')
  await retryContext.close()
  await page.getByRole('button',{name:'Sign out',exact:true}).click()
  check(errors.length===0,'Unexpected browser errors: '+errors.join('; '))
  return {passed:['read-only fictional demo','private empty state','draft creation and exact quantity','correction audit','submit/review/return/cancel','list search and 20-row pagination','stale update rejected in UI','organisation isolation and scoped references','viewer read-only UI','membership switching','phone controls','lost-response retry is idempotent','1440/1024/390/320 form/list/detail containment','zero unexpected main-page browser errors'],generated}
}
