async page => {
  const check = (ok, message) => { if (!ok) throw new Error(message) }
  const origin = 'http://127.0.0.1:5173'
  const random = () => Array.from(crypto.getRandomValues(new Uint8Array(8)), b => b.toString(16).padStart(2, '0')).join('')
  const suffix = random()
  let password = 'Fictional QA ' + random() + '!'
  const names = ['qa-browser-' + suffix + 'a', 'qa-browser-' + suffix + 'b']
  const generated = []
  const errors = []
  async function capture(options) {
    await page.evaluate(() => { document.activeElement?.blur(); window.scrollTo(0, 0) })
    await page.evaluate(() => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve))))
    await page.screenshot(options)
  }
  page.on('pageerror', error => errors.push(error.message))
  page.on('console', msg => { if (msg.type() === 'error') errors.push(msg.text()) })
  async function create(target, index) {
    await target.goto(origin + '/#register')
    await target.getByRole('heading', { name: 'Create an account', exact: true }).waitFor()
    await target.getByLabel('Your name', { exact: true }).fill('Browser QA ' + (index + 1))
    await target.getByLabel('Organisation name', { exact: true }).fill('Browser QA organisation ' + suffix + (index + 1))
    await target.getByLabel('Username', { exact: true }).fill(names[index])
    await target.getByLabel('Password', { exact: true }).fill(password)
    await target.getByRole('button', { name: 'Create account & workspace', exact: true }).click()
    await target.getByRole('heading', { name: 'Aircraft register', exact: true }).waitFor()
    const identity = await (await target.request.get(origin + '/api/auth/session')).json()
    generated.push({ user_id: identity.user.id, workspace_id: identity.workspace.id })
    await page.evaluate(ids => sessionStorage.setItem('sampati-browser-tools-ids', JSON.stringify(ids)), generated)
    return identity
  }
  const navigate = async (target, name) => {
    if (await target.getByRole('button', { name: 'Toggle navigation', exact: true }).isVisible())
      await target.getByRole('button', { name: 'Toggle navigation', exact: true }).click()
    await target.getByRole('navigation', { name: 'Main navigation' }).getByRole('button', { name, exact: name !== 'Aircraft register' }).click()
  }
  await page.setViewportSize({ width: 1440, height: 1000 })
  const owner = await create(page, 0)
  const context2 = await page.context().browser().newContext({ viewport: { width: 1280, height: 900 } })
  const otherPage = await context2.newPage()
  const other = await create(otherPage, 1)
  await navigate(page, 'Import dataset')
  const template = await page.request.get(origin + '/api/examples/template.xlsx')
  check(template.ok(), 'Excel template unavailable')
  await page.getByLabel('Choose aircraft dataset file', { exact: true }).setInputFiles({ name: 'fictional-template.xlsx', mimeType: 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet', buffer: await template.body() })
  await page.getByRole('heading', { name: 'Your dataset is ready to review.', exact: true }).waitFor()
  check((await (await page.request.get(origin + '/api/workspace')).json()).aircraft.length === 0, 'Excel preview wrote records')
  await page.getByRole('button', { name: 'Confirm import', exact: true }).click()
  await page.getByRole('status').filter({ hasText: 'Import complete.' }).waitFor()
  await page.getByRole('button', { name: 'View DEMO-001 details', exact: true }).waitFor()
  for (const format of ['Excel', 'CSV', 'JSON']) {
    const download = page.waitForEvent('download')
    await page.getByRole('button', { name: 'Export ' + format, exact: true }).click()
    check((await download).suggestedFilename().startsWith('sampati-register.'), 'Download filename missing')
  }
  await navigate(page, 'Overview')
  await page.getByRole('heading', { name: 'Reported status', exact: true }).waitFor()
  check((await (await page.request.get(origin + '/api/overview')).json()).total === 1, 'Overview count incorrect')
  await capture({ path: '.impeccable/review/tools-overview.png', fullPage: true })
  await navigate(page, 'Data connections')
  await page.getByLabel('Source name', { exact: true }).fill('Fictional civil file')
  await page.getByRole('button', { name: 'Create connection', exact: true }).click()
  await page.getByRole('heading', { name: 'Save this source key now', exact: true }).waitFor()
  check((await page.getByLabel('Source key', { exact: true }).getAttribute('type')) === 'password', 'Source key is not masked')
  await page.getByRole('button', { name: 'I have saved it', exact: true }).click()
  const before = await (await page.request.get(origin + '/api/workspace')).json()
  check(await page.getByRole('button', { name: 'Generate fictional update', exact: true }).evaluate(el => parseFloat(getComputedStyle(el).minHeight)) >= 40, 'Desktop source action minimum is too small')
  await page.getByRole('button', { name: 'Generate fictional update', exact: true }).click()
  await page.getByRole('status').filter({ hasText: 'A fictional update' }).waitFor()
  const pending = await (await page.request.get(origin + '/api/sources')).json()
  check(pending.incoming[0].state === 'pending', 'Inbox did not receive the update')
  check((await (await page.request.get(origin + '/api/workspace')).json()).revision === before.revision, 'Queued data changed accepted records')
  await capture({ path: '.impeccable/review/tools-inbox.png', fullPage: true })
  await page.getByRole('button', { name: 'Review', exact: true }).click()
  await page.getByRole('heading', { name: 'Your dataset is ready to review.', exact: true }).waitFor()
  await page.getByRole('button', { name: 'Confirm import', exact: true }).click()
  await page.getByRole('status').filter({ hasText: 'Import complete.' }).waitFor()
  check((await (await page.request.get(origin + '/api/sources')).json()).incoming[0].state === 'accepted', 'Inbox acceptance missing')
  await navigate(page, 'Organisation team')
  await page.getByLabel('Teammate username', { exact: true }).fill(names[1])
  await page.getByRole('button', { name: 'Create invitation', exact: true }).click()
  await page.getByRole('heading', { name: 'Invitation code', exact: true }).waitFor()
  const token = await page.locator('.secret-copy input').inputValue()
  await navigate(otherPage, 'Organisation team')
  await otherPage.getByLabel('Invitation code', { exact: true }).fill(token)
  await otherPage.getByRole('button', { name: 'Accept invitation', exact: true }).click()
  await otherPage.getByText('@' + names[0], { exact: true }).waitFor()
  const joined = await (await otherPage.request.get(origin + '/api/auth/session')).json()
  check(joined.workspace.id === owner.workspace.id && joined.workspace.role === 'viewer' && joined.workspaces.length === 2, 'Invitation did not set verified membership')
  await navigate(otherPage, 'Aircraft register')
  await otherPage.getByRole('button', { name: 'View DEMO-001 details', exact: true }).waitFor()
  check(await otherPage.getByRole('navigation', { name: 'Main navigation' }).getByRole('button', { name: 'Import dataset', exact: true }).isDisabled(), 'Viewer import button enabled')
  await otherPage.getByRole('combobox', { name: 'Workspace', exact: true }).selectOption(other.workspace.id)
  await otherPage.getByText('Your register is ready for its first aircraft.', { exact: true }).waitFor()
  await otherPage.getByRole('combobox', { name: 'Workspace', exact: true }).selectOption(owner.workspace.id)
  await otherPage.getByRole('button', { name: 'View DEMO-001 details', exact: true }).waitFor()
  await page.getByRole('button', { name: 'Refresh', exact: true }).click()
  await page.getByLabel('Role for ' + names[1], { exact: true }).selectOption('editor')
  await page.getByRole('status').filter({ hasText: 'Role updated.' }).waitFor()
  await otherPage.reload()
  await otherPage.getByRole('button', { name: 'View DEMO-001 details', exact: true }).waitFor()
  check(!(await otherPage.getByRole('navigation', { name: 'Main navigation' }).getByRole('button', { name: 'Import dataset', exact: true }).isDisabled()), 'Editor import button stayed disabled')
  await capture({ path: '.impeccable/review/tools-team.png', fullPage: true })
  await navigate(page, 'Account settings')
  await page.getByLabel('Current password', { exact: true }).fill(password)
  const nextPassword = 'Changed fictional QA ' + random() + '!'
  await page.getByLabel('New password', { exact: true }).fill(nextPassword)
  await page.getByRole('button', { name: 'Change password', exact: true }).click()
  await page.getByRole('status').filter({ hasText: 'Password changed.' }).waitFor()
  password = nextPassword
  await page.getByLabel('Confirm your password', { exact: true }).fill(password)
  await page.getByRole('button', { name: 'Generate new codes', exact: true }).click()
  await page.getByRole('heading', { name: 'Save all five codes somewhere private', exact: true }).waitFor()
  const codes = await page.locator('.recovery-code-list code').allTextContents()
  check(codes.length === 5, 'Recovery set has wrong length')
  await page.getByRole('button', { name: 'I have saved them', exact: true }).click()
  await capture({ path: '.impeccable/review/tools-account.png', fullPage: true })
  await page.getByRole('button', { name: 'Sign out', exact: true }).click()
  await page.goto(origin + '/#login')
  await page.getByRole('button', { name: 'Use a recovery code', exact: true }).click()
  await page.getByLabel('Username', { exact: true }).fill(names[0])
  await page.getByLabel('Recovery code', { exact: true }).fill(codes[0])
  await page.getByLabel('New password', { exact: true }).fill('Recovered fictional QA ' + random() + '!')
  await page.getByRole('button', { name: 'Reset password & sign in', exact: true }).click()
  await page.getByRole('button', { name: 'View DEMO-001 details', exact: true }).waitFor()
  for (const width of [1024, 390, 320]) {
    await page.setViewportSize({ width, height: 900 })
    for (const view of ['Overview', 'Data connections', 'Organisation team', 'Account settings']) {
      await navigate(page, view)
      await page.locator('.tools-toolbar').waitFor()
      check(await page.locator('.tools-actions .button').evaluateAll(items => items.every(el => el.getBoundingClientRect().height >= 40)), 'Action minimum height below 40px')
      const dimensions = await page.evaluate(() => ({ window: innerWidth, document: document.documentElement.scrollWidth }))
      check(dimensions.document <= dimensions.window, view + ' page overflow at ' + width)
      await capture({ path: '.impeccable/review/tools-' + view.toLowerCase().replaceAll(' ', '-') + '-' + width + '.png', fullPage: true })
    }
    if (width === 390) await capture({ path: '.impeccable/review/tools-account-mobile.png', fullPage: true })
  }
  const touchContext = await page.context().browser().newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true })
  await touchContext.addCookies(await page.context().cookies())
  const touch = await touchContext.newPage()
  await touch.goto(origin + '/#sources')
  await touch.getByRole('heading', { name: 'Connected sources', exact: true }).waitFor()
  check(await touch.locator('.tools-actions .button').evaluateAll(items => items.length > 0 && items.every(el => el.getBoundingClientRect().height >= 44)), 'Touch source actions below 44px')
  await touch.goto(origin + '/#overview')
  await touch.getByRole('heading', { name: 'Source coverage', exact: true }).waitFor()
  check(await touch.locator('.tools-actions .button').evaluateAll(items => items.length > 0 && items.every(el => el.getBoundingClientRect().height >= 44)), 'Touch export actions below 44px')
  await touchContext.close()
  await page.setViewportSize({ width: 1440, height: 1000 })
  await navigate(page, 'Aircraft register')
  await page.getByRole('button', { name: 'Sign out', exact: true }).click()
  await otherPage.getByRole('button', { name: 'Sign out', exact: true }).click()
  await context2.close()
  check(!errors.length, 'Browser errors: ' + errors.join('; '))
  return { passed: ['Excel template and preview/confirm', 'three export downloads', 'overview counts', 'source key masked', 'queued update leaves accepted records unchanged', 'inbox review and acceptance', 'targeted team invitation', 'viewer UI restrictions', 'multiple organisations', 'role updates', 'password change', 'recovery codes and account recovery', 'four new views at 1024/390/320px', 'no new browser errors'], generated }
}
