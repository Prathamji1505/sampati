async page => {
  const check = (condition, message) => { if (!condition) throw new Error(message) }
  const origin = 'http://127.0.0.1:5173'
  const suffix = Array.from(crypto.getRandomValues(new Uint8Array(7)), byte => byte.toString(16).padStart(2, '0')).join('')
  const password = 'Fictional check ' + Array.from(crypto.getRandomValues(new Uint8Array(16)), byte => byte.toString(16).padStart(2, '0')).join('') + '!'
  const names = ['qa-browser-' + suffix + 'a', 'qa-browser-' + suffix + 'b']
  const generated = []
  const errors = []
  const onError = message => { if (message.type() === 'error') errors.push(message.text()) }
  page.on('console', onError)
  async function createAccount(target, index) {
    await target.goto(origin + '/#register')
    await target.getByRole('heading', { name: 'Create an account', exact: true }).waitFor()
    await target.getByLabel('Your name', { exact: true }).fill('Browser QA ' + (index + 1))
    await target.getByLabel('Organisation name', { exact: true }).fill('Browser QA organisation ' + suffix + (index + 1))
    await target.getByLabel('Username', { exact: true }).fill(names[index])
    await target.getByLabel('Password', { exact: true }).fill(password)
    await target.getByRole('button', { name: 'Create account & workspace', exact: true }).click()
    await target.getByRole('heading', { name: 'Aircraft register', exact: true }).waitFor()
    await target.getByText('Your register is ready for its first aircraft.', { exact: true }).waitFor()
    const identity = await (await target.request.get(origin + '/api/auth/session')).json()
    generated.push({ user_id: identity.user.id, workspace_id: identity.workspace.id })
    await page.evaluate(ids => sessionStorage.setItem('sampati-browser-qa-ids', JSON.stringify(ids)), generated)
    return identity
  }
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.goto(origin + '/#login')
  await page.getByRole('heading', { name: 'Welcome back', exact: true }).waitFor()
  await page.screenshot({ path: '.impeccable/review/accounts-login.png', fullPage: true })
  const first = await createAccount(page, 0)
  check(first.workspace.role === 'owner', 'New account is not an organisation owner')
  await page.getByRole('button', { name: 'Try sample data', exact: true }).click()
  await page.getByRole('heading', { name: 'Your dataset is ready to review.', exact: true }).waitFor()
  const empty = await (await page.request.get(origin + '/api/workspace')).json()
  check(empty.aircraft.length === 0, 'Private preview unexpectedly saved records')
  await page.getByRole('button', { name: 'Confirm import', exact: true }).click()
  await page.getByRole('status').filter({ hasText: 'Import complete.' }).waitFor()
  await page.getByRole('button', { name: 'View DEMO-001 details', exact: true }).waitFor()
  const accepted = await (await page.request.get(origin + '/api/workspace')).json()
  check(accepted.aircraft.length === 12 && accepted.imports[0].actor.includes(names[0]), 'Private import/actor was not saved')
  await page.screenshot({ path: '.impeccable/review/accounts-private.png', fullPage: true })
  await page.reload()
  await page.getByRole('button', { name: 'View DEMO-001 details', exact: true }).waitFor()
  check((await (await page.request.get(origin + '/api/auth/session')).json()).user.id === first.user.id, 'Reload lost the account session')
  await page.getByRole('combobox', { name: 'Workspace', exact: true }).selectOption('demo')
  await page.getByText('DEMO', { exact: true }).waitFor()
  await page.getByRole('combobox', { name: 'Workspace', exact: true }).selectOption(first.workspace.id)
  await page.getByText('PRIVATE', { exact: true }).waitFor()
  const context2 = await page.context().browser().newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true })
  const secondPage = await context2.newPage()
  await secondPage.goto(origin + '/#register')
  await secondPage.getByRole('heading', { name: 'Create an account', exact: true }).waitFor()
  await secondPage.screenshot({ path: '.impeccable/review/accounts-register-mobile.png', fullPage: true })
  const second = await createAccount(secondPage, 1)
  check(second.workspace.id !== first.workspace.id, 'Two accounts were given the same organisation')
  const other = await (await secondPage.request.get(origin + '/api/workspace')).json()
  check(other.aircraft.length === 0 && other.imports.length === 0, 'Second organisation can see the first organisation records')
  const foreign = await secondPage.request.get(origin + '/api/imports/' + accepted.imports[0].id)
  check(foreign.status() === 404, 'Cross-organisation import could be read')
  const layout = await secondPage.evaluate(() => ({ viewport: innerWidth, document: document.documentElement.scrollWidth }))
  check(layout.document <= layout.viewport, 'Private mobile page overflows')
  await secondPage.getByRole('button', { name: 'Toggle navigation', exact: true }).click()
  await secondPage.getByRole('button', { name: 'Sign out', exact: true }).click()
  await secondPage.getByText('DEMO', { exact: true }).waitFor()
  check((await secondPage.request.get(origin + '/api/workspace')).status() === 401, 'Sign-out did not protect private data')
  await context2.close()
  await page.getByRole('button', { name: 'Sign out', exact: true }).click()
  await page.getByText('DEMO', { exact: true }).waitFor()
  await page.goto(origin + '/#login')
  await page.getByLabel('Username', { exact: true }).fill(names[0])
  await page.getByLabel('Password', { exact: true }).fill(password)
  await page.getByRole('button', { name: 'Sign in', exact: true }).click()
  await page.getByRole('button', { name: 'View DEMO-001 details', exact: true }).waitFor()
  check((await (await page.request.get(origin + '/api/workspace')).json()).aircraft.length === 12, 'Signing back in lost private records')
  await page.getByRole('button', { name: 'Sign out', exact: true }).click()
  await page.getByText('DEMO', { exact: true }).waitFor()
  page.off('console', onError)
  check(!errors.length, 'Browser console errors: ' + errors.join('; '))
  return { passed: ['sign-up', 'empty private workspace', 'private preview does not save', 'private import', 'attributable actor', 'session after reload', 'demo/private switching', 'two-browser organisation isolation', 'foreign import blocked', 'mobile layout', 'sign-out', 'sign back in with saved records'], generated }
}
