async page => {
  const check = (ok, message) => { if (!ok) throw new Error(message) }
  const origin = 'http://127.0.0.1:5173'
  const suffix = crypto.randomUUID().replaceAll('-', '').slice(0, 14)
  const errors = []
  page.on('console', message => { if (message.type() === 'error') errors.push(message.text()) })
  page.on('pageerror', error => errors.push(error.message))
  const data = async path => (await page.request.get(origin + '/api' + path)).json()
  const csv = rows => {
    const headers = ['aircraft_id', 'display_name', 'reported_status', 'source_updated_at', 'source_name', 'note']
    return headers.join(',') + '\n' + rows.map(row => headers.map(key => '"' + row[key].replaceAll('"','""') + '"').join(',')).join('\n')
  }
  async function navigate(name) {
    if (await page.getByRole('button', { name: 'Toggle navigation', exact: true }).isVisible()) await page.getByRole('button', { name: 'Toggle navigation', exact: true }).click()
    await page.getByRole('navigation', { name: 'Main navigation' }).getByRole('button', { name, exact: true }).click()
  }
  async function capture(name) {
    await page.evaluate(async () => { await document.fonts.ready; document.activeElement?.blur(); scrollTo(0,0); await new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve))) })
    await page.screenshot({ path: '.impeccable/review/' + name, fullPage: true })
  }
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.goto(origin + '/#register')
  await page.getByLabel('Your name', { exact: true }).fill('Browser QA report checks')
  await page.getByLabel('Organisation name', { exact: true }).fill('Browser QA organisation checks ' + suffix)
  await page.getByLabel('Username', { exact: true }).fill('qa-browser-' + suffix)
  await page.getByLabel('Password', { exact: true }).fill('Fictional QA ' + crypto.randomUUID())
  await page.getByRole('button', { name: 'Create account & workspace', exact: true }).click()
  await page.getByRole('heading', { name: 'Aircraft register', exact: true }).waitFor()
  const identity = await data('/auth/session')
  await page.evaluate(value => sessionStorage.setItem('sampati-quality-qa-id', value), identity.user.id)
  await navigate('Report checks')
  await page.getByRole('heading', { name: 'No accepted reports to check yet.', exact: true }).waitFor()
  const now = Date.now()
  const rows = Array.from({ length: 23 }, (_, index) => ({ aircraft_id: 'CIV-' + String(index + 1).padStart(3,'0'),
    display_name: index === 3 ? '' : 'Fictional civil aircraft ' + (index + 1),
    reported_status: index === 2 ? 'unknown' : index === 4 ? 'unavailable' : 'available',
    source_updated_at: new Date(now + (index === 1 ? -30*3600000 : index === 2 ? 10*60000 : 0)).toISOString(),
    source_name: 'Fictional civil report register', note: 'Browser QA only.' }))
  await navigate('Import dataset')
  await page.getByLabel('Choose aircraft dataset file', { exact: true }).setInputFiles({ name: 'fictional-report-checks.csv', mimeType: 'text/csv', buffer: Buffer.from(csv(rows)) })
  await page.getByRole('heading', { name: 'Your dataset is ready to review.', exact: true }).waitFor()
  await page.getByRole('button', { name: 'Confirm import', exact: true }).click()
  await page.getByRole('status').filter({ hasText: 'Import complete.' }).waitFor()
  const before = await data('/workspace')
  await navigate('Report checks')
  await page.getByText('Page 1 of 2', { exact: true }).waitFor()
  const report = await data('/report-checks')
  check(report.summary.records === 23 && report.summary.needs_review === 3, 'Initial report counts incorrect')
  check(await page.locator('.quality-table tbody tr').count() === 20, 'Pagination first page incorrect')
  await page.getByRole('button', { name: 'Next', exact: true }).click()
  check(await page.locator('.quality-table tbody tr').count() === 3, 'Pagination second page incorrect')
  await page.getByRole('button', { name: 'Previous', exact: true }).click()
  await page.getByRole('combobox', { name: 'Filter by finding', exact: true }).selectOption('stale_report')
  check(await page.locator('.quality-table tbody tr').count() === 1, 'Finding filter incorrect')
  await page.locator('.quality-findings summary').click()
  await page.getByText('Request a newer report from the source.', { exact: true }).waitFor()
  check(await page.getByText('Reported available', { exact: true }).isVisible(), 'Data finding rewrote reported status')
  await page.getByRole('button', { name: 'Inspect CIV-002 report', exact: true }).click()
  await page.getByRole('dialog').waitFor()
  await page.getByRole('button', { name: 'Close details', exact: true }).click()
  const downloadPromise = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Export filtered results', exact: true }).click()
  const download = await downloadPromise
  const chunks = []
  for await (const chunk of await download.createReadStream()) chunks.push(chunk)
  const exported = JSON.parse(Buffer.concat(chunks).toString('utf8'))
  check(exported.record_count === 1 && exported.records[0].aircraft_id === 'CIV-002' && exported.rule_version === 'report-data-v1', 'Filtered export contents incorrect')
  await page.getByRole('textbox', { name: 'Search report checks', exact: true }).fill('no-such-report')
  await page.getByRole('heading', { name: 'No reports match these filters.', exact: true }).waitFor()
  await page.getByRole('button', { name: 'Clear filters', exact: true }).click()
  await page.getByRole('button', { name: /^Complete reports/ }).click()
  check(await page.locator('.quality-table tbody tr').count() === 20, 'Complete-report filter incorrect')
  const after = await data('/workspace')
  check(after.revision === before.revision && JSON.stringify(after.aircraft) === JSON.stringify(before.aircraft) && JSON.stringify(after.imports) === JSON.stringify(before.imports), 'Read-only checks changed accepted records')
  await navigate('Data connections')
  await page.getByLabel('Source name', { exact: true }).fill('Fictional checks evidence')
  const connectionResponse = page.waitForResponse(response => response.url().endsWith('/api/sources') && response.request().method() === 'POST')
  await page.getByRole('button', { name: 'Create connection', exact: true }).click()
  const source = await (await connectionResponse).json()
  await page.getByRole('button', { name: 'I have saved it', exact: true }).click()
  const incomingRows = [{ ...rows[0], reported_status: 'unavailable' }, { ...rows[5], source_updated_at: new Date(now+1000).toISOString() }, { ...rows[0], aircraft_id: 'CIV-NEW' }]
  const received = await page.request.post(origin + '/api/ingest/' + source.id, { headers: { Authorization: 'Bearer ' + source.token }, multipart: { file: { name: 'fictional-incoming.csv', mimeType: 'text/csv', buffer: Buffer.from(csv(incomingRows)) } } })
  check(received.status() === 202, 'Incoming evidence upload failed')
  await navigate('Report checks')
  await page.getByRole('button', { name: 'Open incoming inbox', exact: true }).waitFor()
  await page.getByRole('button', { name: /^Needs review/ }).click()
  const firstRow = page.locator('.quality-table tbody tr').filter({ hasText: 'CIV-001' })
  await firstRow.locator('summary').click()
  await firstRow.getByText('An incoming report disagrees at the same source timestamp.', { exact: true }).waitFor()
  for (const width of [1440, 1024, 390, 320]) {
    await page.setViewportSize({ width, height: 1000 })
    const size = await page.evaluate(() => ({ viewport: innerWidth, document: document.documentElement.scrollWidth }))
    check(size.document <= size.viewport, 'Report checks overflow at ' + width)
    await capture('report-checks-' + width + '.png')
  }
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.getByRole('button', { name: 'Open incoming inbox', exact: true }).click()
  await page.getByRole('heading', { name: 'Data connections', exact: true }).waitFor()
  await page.getByRole('button', { name: 'Reject', exact: true }).click()
  await page.getByRole('status').filter({ hasText: 'Incoming dataset rejected.' }).waitFor()
  await navigate('Report checks')
  const finalReport = await data('/report-checks')
  check(finalReport.summary.needs_review === 3 && finalReport.summary.pending_files === 0, 'Rejected inbox evidence remains flagged')
  const touchContext = await page.context().browser().newContext({ viewport: { width: 390, height: 844 }, hasTouch: true, isMobile: true })
  await touchContext.addCookies(await page.context().cookies())
  const touch = await touchContext.newPage()
  await touch.goto(origin + '/#checks')
  await touch.getByRole('button', { name: 'Export filtered results', exact: true }).waitFor()
  check(await touch.getByRole('button', { name: 'Refresh checks', exact: true }).evaluate(el => el.getBoundingClientRect().height >= 44), 'Touch action below 44px')
  check(await touch.getByRole('textbox', { name: 'Search report checks', exact: true }).evaluate(el => parseFloat(getComputedStyle(el).fontSize) >= 16), 'Touch search text below 16px')
  await touch.route('**/api/report-checks', route => route.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ detail: 'Fictional temporary unavailability.' }) }))
  await touch.reload()
  await touch.getByRole('heading', { name: 'Report checks are unavailable.', exact: true }).waitFor()
  await touch.unroute('**/api/report-checks')
  await touch.getByRole('button', { name: 'Refresh checks', exact: true }).click()
  await touch.getByText('Page 1 of 2', { exact: true }).waitFor()
  await touchContext.close()
  await page.getByRole('button', { name: 'Sign out', exact: true }).click()
  check(errors.length === 0, 'Unexpected browser errors: ' + errors.join('; '))
  return { passed: ['empty state', '23-report import', 'explainable findings', 'finding/result/search filters', '20-row pagination', 'filtered JSON contents', 'source details', 'checks and export leave accepted records unchanged', 'incoming conflict and newer report evidence', 'inbox navigation and rejection refresh', '1440/1024/390/320 layouts', 'touch controls', '503 error and retry', 'zero unexpected browser errors'], generated_user_id: identity.user.id }
}
