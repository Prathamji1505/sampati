async page => {
  const check = (condition, message) => { if (!condition) throw new Error(message) }
  const origin = 'http://127.0.0.1:5173'
  const state = async () => (await page.request.get(origin + '/api/demo/workspace')).json()
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.goto(origin + '/#demo/workspace')
  await page.getByRole('heading', { name: 'Aircraft register', exact: true }).waitFor()
  const before = await state()
  if (before.aircraft.length === 0) {
    await page.getByRole('button', { name: 'Try sample data', exact: true }).click()
  } else {
    await page.getByRole('button', { name: 'Import dataset', exact: true }).first().click()
    await page.getByRole('button', { name: 'Use sample', exact: true }).click()
  }
  await page.getByRole('heading', { name: 'Your dataset is ready to review.', exact: true }).waitFor()
  check((await state()).revision === before.revision, 'Preview unexpectedly changed the database')
  await page.screenshot({ path: '.impeccable/review/import-preview.png', fullPage: true })
  await page.getByRole('button', { name: 'Confirm import', exact: true }).click()
  await page.getByRole('status').filter({ hasText: 'Import complete.' }).waitFor()
  let saved = await state()
  check(saved.aircraft.length >= 12, 'Sample import did not persist twelve aircraft')
  await page.getByRole('textbox', { name: 'Search aircraft or source' }).fill('DEMO-003')
  check(await page.locator('.aircraft-table tbody tr').count() === 1, 'Search did not filter the table')
  await page.getByRole('textbox', { name: 'Search aircraft or source' }).fill('')
  await page.getByRole('button', { name: /^Available \d+$/ }).click()
  check(await page.locator('.aircraft-table tbody tr').count() === saved.aircraft.filter(row => row.reported_status === 'available').length, 'Status filter count is wrong')
  await page.getByRole('button', { name: /^All aircraft \d+$/ }).click()
  await page.getByRole('combobox', { name: 'Filter by report freshness' }).selectOption('review')
  check(await page.locator('.aircraft-table tbody tr').count() === saved.aircraft.filter(row => row.freshness !== 'current').length, 'Freshness filter count is wrong')
  await page.getByRole('combobox', { name: 'Filter by report freshness' }).selectOption('all')
  await page.getByRole('button', { name: 'View DEMO-001 details', exact: true }).click()
  await page.getByRole('dialog').waitFor()
  check(await page.getByRole('dialog').getByText('Fictional civil fleet register', { exact: true }).isVisible(), 'Aircraft source is missing in details')
  await page.getByRole('button', { name: 'Close details', exact: true }).click()
  await page.getByRole('button', { name: 'Import history', exact: true }).click()
  await page.locator('.history-row').first().click()
  await page.getByRole('dialog').waitFor()
  check(await page.locator('.audit-change').count() === 12, 'Import audit is missing changed aircraft')
  await page.getByRole('button', { name: 'Close details', exact: true }).click()
  await page.getByRole('button', { name: 'Import dataset', exact: true }).first().click()
  const headers = ['aircraft_id', 'display_name', 'reported_status', 'source_updated_at', 'source_name', 'note']
  const csv = rows => headers.join(',') + '\n' + rows.map(row => headers.map(key => '"' + row[key].replaceAll('"', '""') + '"').join(',')).join('\n') + '\n'
  const acceptedRows = saved.aircraft.map(row => Object.fromEntries(headers.map(key => [key, row[key]])))
  await page.locator('input[type=file]').setInputFiles({ name: 'repeat.csv', mimeType: 'text/csv', buffer: Buffer.from(csv(acceptedRows)) })
  // The first sample was canonically normalized, so equivalent saved rows must replay safely.
  await page.getByRole('heading', { name: 'This dataset is already in your history.', exact: true }).waitFor()
  const revision = saved.revision
  await page.getByRole('button', { name: 'Confirm no changes', exact: true }).click()
  await page.getByRole('status').filter({ hasText: 'already imported' }).waitFor()
  check((await state()).revision === revision, 'Repeat upload changed the revision')
  await page.getByRole('button', { name: 'Import dataset', exact: true }).first().click()
  await page.getByRole('button', { name: 'Choose another file', exact: true }).count().then(async count => { if (count) await page.getByRole('button', { name: 'Choose another file', exact: true }).click() })
  await page.locator('input[type=file]').setInputFiles({ name: 'invalid.csv', mimeType: 'text/csv', buffer: Buffer.from(csv([{ ...acceptedRows[0], reported_status: 'ready' }])) })
  await page.getByRole('heading', { name: 'A few things need your attention.', exact: true }).waitFor()
  check(await page.getByRole('button', { name: 'Confirm import', exact: true }).isDisabled(), 'Invalid batch can be confirmed')
  check((await state()).revision === revision, 'Invalid preview changed the database')
  await page.screenshot({ path: '.impeccable/review/invalid-import.png', fullPage: true })
  await page.getByRole('button', { name: /^Aircraft register \d+$/ }).click()
  await page.screenshot({ path: '.impeccable/review/desktop.png', fullPage: true })
  await page.reload()
  await page.getByRole('button', { name: 'View DEMO-001 details', exact: true }).waitFor()
  await page.setViewportSize({ width: 390, height: 844 })
  await page.screenshot({ path: '.impeccable/review/mobile.png', fullPage: true })
  const layout = await page.evaluate(() => ({ viewport: innerWidth, document: document.documentElement.scrollWidth }))
  check(layout.document <= layout.viewport, 'Mobile page overflows outside the table')
  await page.getByRole('button', { name: 'Toggle navigation', exact: true }).click()
  await page.getByRole('button', { name: 'Workspace guide', exact: true }).click()
  await page.getByRole('heading', { name: 'Your workspace, explained', exact: true }).waitFor()
  await page.screenshot({ path: '.impeccable/review/mobile-guide.png', fullPage: true })
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.getByRole('button', { name: /^Aircraft register \d+$/ }).click()
  return { passed: ['preview does not save', 'confirmed import persists', 'search', 'status filter', 'freshness filter', 'aircraft details', 'import audit', 'repeat upload is a no-op', 'invalid file cannot be confirmed', 'reload persistence', 'mobile no page overflow', 'mobile navigation'], aircraft: (await state()).aircraft.length }
}
